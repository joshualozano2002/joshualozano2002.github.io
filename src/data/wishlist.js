export const allItems = christmas.groups.flatMap((g) => g.items)
export const pricedItems = allItems.filter((i) => i.low != null)

const sum = (items, key) => items.reduce((total, i) => total + i[key], 0)

/** Per-group figures, so a hold can print its own subtotal. */
export const groupTotals = Object.fromEntries(
  christmas.groups.map((g) => {
    const priced = g.items.filter((i) => i.low != null)
    return [
      g.id,
      {
        count: g.items.length,
        priced: priced.length,
        low: sum(priced, 'low'),
        high: sum(priced, 'high'),
        // The midpoint is what the payload bar is drawn from: a range should
        // weigh its middle, not whichever end flatters the chart.
        mid: (sum(priced, 'low') + sum(priced, 'high')) / 2,
      },
    ]
  }),
)

export const totals = {
  items: allItems.length,
  priced: pricedItems.length,
  open: allItems.length - pricedItems.length,
  low: sum(pricedItems, 'low'),
  high: sum(pricedItems, 'high'),
}
